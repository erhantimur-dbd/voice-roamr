export function isLocale(code: string): code is LocaleCode {
  return LOCALES.some((l) => l.code === code);
}

export function t(locale: string, key: MsgKey): string {
  const loc = isLocale(locale) ? locale : "en";
  if (loc === "en") return EN[key];
  return EXTRA[loc]?.[key] ?? EN[key];
}

export function readStoredLocale(): LocaleCode {
  if (typeof window === "undefined") return "en";
  try {
    const q = new URLSearchParams(window.location.search).get("hl");
    if (q && isLocale(q)) return q;
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored && isLocale(stored)) return stored;
  } catch {
    /* ignore */
  }
  return "en";
}

export function writeStoredLocale(code: LocaleCode) {
  try {
    window.localStorage.setItem(STORAGE_KEY, code);
    const url = new URL(window.location.href);
    url.searchParams.set("hl", code);
    window.history.replaceState({}, "", url);
  } catch {
    /* ignore */
  }
}

export { LOCALES, STORAGE_KEY };
